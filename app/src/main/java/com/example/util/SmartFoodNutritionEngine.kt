    /**
     * Detects if the user is asking PikaBot for:
     * 1) A specific exercise (e.g., "bench press", "incline dumbbell press", "lateral raise", "deadlift", "squats", "bicep curl", "pushups"),
     * 2) Specific muscle group exercises (e.g., "chest exercises", "upper chest", "bicep exercises", "tricep workout", "shoulder exercises", "back exercises", "leg workout", "abs exercises", "forearm exercises"), or
     * 3) A full Weekly Workout / Exercise Plan (e.g., "give me an exercise plan", "workout plan for weight gain", "workout plan for weight loss", "push pull legs", "home workout plan").
     */
    fun detectAndBuildExerciseOrWorkoutResponse(
        query: String,
        bio: HunterBiometrics
    ): ExerciseCoachRecommendation? {
        val qLower = query.trim().lowercase()
        if (qLower.isBlank()) return null

        // Do not intercept if the user is explicitly asking for food/grams/diet/recipes only
        val pureFoodIndicators = listOf(
            "kcal", "calorie", "gram", "grams", "protein in", "macros in",
            "dosa", "idli", "idly", "biryani", "biriyani", "shawarma", "fries", "burger", "pizza",
            "chicken gravy", "chicken curry", "paneer", "dal", "roti", "chapati", "parotta", "poha", "upma", "pongal",
            "creatine", "whey", "oats", "egg", "mutton", "fish", "rice", "sambar", "chutney", "momos", "noodles"
        )
        val hasWorkoutWord = listOf(
            "exercise", "exercises", "workout", "workouts", "routine", "split", "gym",
            "chest", "pec", "bicep", "tricep", "shoulder", "delt", "lat", "lats", "back workout", "back exercise",
            "quad", "hamstring", "calf", "calves", "glute", "abs", "six pack", "core", "forearm", "trap",
            "bench press", "incline press", "deadlift", "squat", "pushup", "push up", "pullup", "pull up",
            "chinup", "pulldown", "row", "curl", "pushdown", "skull crusher", "lateral raise", "face pull",
            "lunge", "leg press", "hip thrust", "plank", "crunch", "burpee", "hiit", "ppl", "push pull", "bro split"
        ).any { qLower.contains(it) }

        if (!hasWorkoutWord && pureFoodIndicators.any { qLower.contains(it) }) {
            return null
        }
        if (!hasWorkoutWord) {
            return null
        }

        // =========================================================================
